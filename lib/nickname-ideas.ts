// 주사위(다른 별명) 버튼: 현재 별명을 즉시 반복하지 않고, 나머지 후보 전체에서 고른다.
// roll은 [0, 1) 난수. 후보가 넉넉하므로 두 개만 왕복하는 일이 없다.
export function pickDifferentNickname(ideas: readonly string[], current: string, roll: number) {
  const pool = ideas.filter((idea) => idea !== current);
  if (!pool.length) return FALLBACK_NICKNAME;
  const index = Math.min(pool.length - 1, Math.max(0, Math.floor(roll * pool.length)));
  return pool[index] ?? FALLBACK_NICKNAME;
}
